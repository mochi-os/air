"""Bake the geoid, mean sea level, into the flight core (world/games/air/flight/geoid.go)
and the client (web/src/game/geoid.ts): EGM2008's height above the WGS84 ellipsoid at
every whole degree of latitude and longitude, in decimetres. Both hosts interpolate the
same table bilinearly, so the sea a jet meets and the sea the client draws are one surface.

Source: the US National Geospatial-Intelligence Agency's Earth Gravitational Model 2008,
as GeographicLib distributes its 5-minute grid (egm2008-5.pgm, a 16-bit PGM whose header
gives the offset and scale, rows from 90 N, columns from 0 E):
  https://sourceforge.net/projects/geographiclib/files/geoids-distrib/egm2008-5.tar.bz2
The table takes the grid's own values at the whole-degree nodes; between them a 1-degree
bilinear surface departs from the full model by at most a few metres, under steep trenches.

Usage: geoid.py <egm2008-5.pgm>
"""
import base64
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent  # apps/air
GO = ROOT.parent.parent / "world/games/air/flight/geoid.go"
TS = ROOT / "web/src/game/geoid.ts"
ROWS, COLUMNS = 181, 361  # 90 N to 90 S, 180 W to 180 E, whole degrees


def read(path):
    """The PGM's width, height, offset, scale and big-endian samples."""
    data = Path(path).read_bytes()
    if not data.startswith(b"P5"):
        raise ValueError("not a binary PGM")
    offset = scale = None
    fields = []
    at = 2
    while len(fields) < 3:
        while data[at:at + 1].isspace():
            at += 1
        if data[at:at + 1] == b"#":
            end = data.index(b"\n", at)
            comment = data[at + 1:end].decode().split()
            if len(comment) == 2 and comment[0] == "Offset":
                offset = float(comment[1])
            if len(comment) == 2 and comment[0] == "Scale":
                scale = float(comment[1])
            at = end + 1
            continue
        end = at
        while not data[end:end + 1].isspace():
            end += 1
        fields.append(int(data[at:end]))
        at = end
    width, height, most = fields
    if most != 65535 or offset is None or scale is None:
        raise ValueError("not a GeographicLib geoid grid")
    at += 1  # the single whitespace before the samples
    samples = data[at:at + width * height * 2]
    if len(samples) != width * height * 2:
        raise ValueError("the grid is short")
    return width, height, offset, scale, samples


def nodes(path):
    """The geoid's height at every whole degree, decimetres, row by row from 90 N, each row
    from 180 W to 180 E inclusive (the last column repeats the first)."""
    width, height, offset, scale, samples = read(path)
    if (width - 0) % 360 or (height - 1) % 180:
        raise ValueError("the grid is not whole degrees")
    per = width // 360  # samples a degree
    if (height - 1) // 180 != per:
        raise ValueError("rows and columns differ in spacing")
    table = []
    for row in range(ROWS):
        latitude_row = row * per  # 90 N down
        for column in range(COLUMNS):
            longitude = column - 180  # 180 W to 180 E
            x = (longitude % 360) * per
            (value,) = struct.unpack_from(">H", samples, (latitude_row * width + x) * 2)
            metres = offset + scale * value
            table.append(round(metres * 10))
    return table


def go(table):
    lines = [
        "// Mochi world: the geoid",
        "// Copyright © 2026 Mochisoft OÜ",
        "// SPDX-License-Identifier: AGPL-3.0-only",
        "// This file is part of Mochi, licensed under the GNU AGPL v3 with the",
        "// Mochi Application Interface Exception - see license.txt and license-exception.md.",
        "",
        "// GENERATED by apps/air/tools/geoid.py from EGM2008 - do not edit by hand.",
        "",
        "package flight",
        "",
        "// geoid is mean sea level's height above the WGS84 ellipsoid at every whole",
        "// degree, decimetres: 181 rows from 90 N to 90 S, each of 361 columns from 180 W",
        "// to 180 E (the last repeats the first).",
        "var geoid = [181 * 361]int16{",
    ]
    for row in range(ROWS):
        values = table[row * COLUMNS:(row + 1) * COLUMNS]
        lines.append("\t" + ", ".join(str(v) for v in values) + ",")
    lines.append("}")
    return "\n".join(lines) + "\n"


def ts(table):
    packed = base64.b64encode(struct.pack("<%dh" % len(table), *table)).decode()
    return "\n".join([
        "// Copyright © 2026 Mochisoft OÜ",
        "// SPDX-License-Identifier: AGPL-3.0-only",
        "// This file is part of Mochi, licensed under the GNU AGPL v3 with the",
        "// Mochi Application Interface Exception - see license.txt and license-exception.md.",
        "// GENERATED by tools/geoid.py from EGM2008 - do not edit by hand.",
        "// Mean sea level's height above the WGS84 ellipsoid at every whole degree, decimetres:",
        "// 181 rows from 90 N to 90 S, each of 361 columns from 180 W to 180 E (the last repeats",
        "// the first), as little-endian 16-bit integers. The flight core's geoid.go is the same.",
        "export const ROWS = 181",
        "export const COLUMNS = 361",
        f"export const GEOID = '{packed}'",
        "",
    ])


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    table = nodes(sys.argv[1])
    GO.write_text(go(table))
    TS.write_text(ts(table))
    print(f"wrote {GO} and {TS}: {len(table)} nodes, {min(table) / 10:.1f} to {max(table) / 10:.1f} m")


if __name__ == "__main__":
    main()
